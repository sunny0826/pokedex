export type TranslationKey = keyof typeof translations.zh;

export const translate = (
  language: AppLanguage,
  key: TranslationKey,
  params?: TranslationParams
): string => {
  return interpolate(translations[language][key] ?? translations[DEFAULT_LANGUAGE][key] ?? key, params);
};

export interface PokeApiLocalizedEntry {
  language: { name: string };
}

export const findPokeApiLocalizedEntry = <T extends PokeApiLocalizedEntry>(
  entries: T[] | undefined,
  language: PokeApiLanguage,
  fallbackLanguages: PokeApiLanguage[] = ['en', 'zh-hans']
): T | undefined => {
  if (!entries?.length) return undefined;

  const normalizedLanguage = language.toLowerCase();
  const exactMatch = entries.find((entry) => entry.language.name.toLowerCase() === normalizedLanguage);
  if (exactMatch) return exactMatch;

  const fallbackMatch = fallbackLanguages
    .filter((fallbackLanguage) => fallbackLanguage !== language)
    .map((fallbackLanguage) => fallbackLanguage.toLowerCase())
    .map((fallbackLanguage) =>
      entries.find((entry) => entry.language.name.toLowerCase() === fallbackLanguage)
    )
    .find(Boolean);

  return fallbackMatch ?? entries[0];
};

export const cleanPokeApiText = (text: string): string => text.replace(/\n|\f/g, ' ');
