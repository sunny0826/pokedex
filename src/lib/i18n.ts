export type AppLanguage = 'zh' | 'en';
export type PokeApiLanguage = 'zh-hans' | 'en';

export const DEFAULT_LANGUAGE: AppLanguage = 'zh';
export const LANGUAGE_STORAGE_KEY = 'pokedex-language';

export const appLanguageToPokeApiLanguage: Record<AppLanguage, PokeApiLanguage> = {
  zh: 'zh-hans',
  en: 'en',
};

export const appLanguageToHtmlLanguage: Record<AppLanguage, string> = {
  zh: 'zh-Hans',
  en: 'en',
};

export const normalizeLanguage = (value: string | null | undefined): AppLanguage => {
  return value === 'en' || value === 'zh' ? value : DEFAULT_LANGUAGE;
};

export type TranslationParams = Record<string, string | number>;

const interpolate = (template: string, params?: TranslationParams): string => {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
};

